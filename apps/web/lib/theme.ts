/**
 * Steward's own look comes from a Steward system: the fixture's tokens,
 * turned into a Tailwind v4 `@theme`. Tailwind's default colors and spacing
 * are cleared first, so the app can only use the system's values: off-system
 * classes like `bg-sky-500` or `p-5` simply don't exist. Pure.
 */
import { isToken, type SystemModel, type Token, type TokenGroup } from "@steward/model";

interface Entry {
  path: string[];
  token: Token;
}

function tokens(group: TokenGroup, path: string[] = []): Entry[] {
  return Object.entries(group)
    .filter(([k]) => !k.startsWith("$"))
    .flatMap(([k, v]) => (v && typeof v === "object" ? (isToken(v) ? [{ path: [...path, k], token: v }] : tokens(v as TokenGroup, [...path, k])) : []));
}

/** `color.gray.50` → `gray-50`; `spacing.2_5` → `2\.5` (Tailwind's name for `p-2.5`). */
const colorName = (path: string[]) => path.slice(1).join("-");
const spacingName = (path: string[]) => path.slice(1).join("-").replace("_", "\\.");

const byNumber = (a: string, b: string) => a.localeCompare(b, "en", { numeric: true });

function colorValue(token: Token): string {
  if (token.$type !== "color") throw new Error("not a color");
  const { hex, alpha } = token.$value;
  return alpha === undefined || alpha >= 1 ? hex : `${hex}${Math.round(alpha * 255).toString(16).padStart(2, "0")}`;
}

/** Pure: the `@theme` CSS for a system's color and spacing tokens, sorted, with a header saying where it came from. */
export function themeCss(model: SystemModel, source: string): string {
  const all = tokens(model.tokens);
  const colors = all
    .filter((e) => e.path[0] === "color" && e.token.$type === "color")
    .map((e) => [colorName(e.path), colorValue(e.token)] as const)
    .sort(([a], [b]) => byNumber(a, b));
  const spacing = all
    .filter((e) => e.path[0] === "spacing" && e.token.$type === "dimension")
    .map((e) => {
      const { value, unit } = (e.token as Extract<Token, { $type: "dimension" }>).$value;
      return [spacingName(e.path), `${value}${unit}`] as const;
    })
    .sort(([a], [b]) => byNumber(a.replace("\\", ""), b.replace("\\", "")));

  return [
    `/* Generated by \`pnpm -F web theme\` from ${source}. Don't edit by hand. */`,
    "",
    "@theme {",
    "  /* Only the system's values: Tailwind's defaults are cleared. */",
    "  --color-*: initial;",
    "  --spacing: initial;",
    "  --spacing-*: initial;",
    "",
    ...colors.map(([name, value]) => `  --color-${name}: ${value};`),
    "",
    ...spacing.map(([name, value]) => `  --spacing-${name}: ${value};`),
    "}",
    "",
  ].join("\n");
}
