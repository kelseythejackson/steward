// Sections
// ---------------------------------------------------------------------------

interface Parts {
  colors: { path: string; token: ColorToken }[];
  spacing: { path: string; token: DimensionToken }[];
  components: ComponentEntry[];
  /** Components merged into another by an accepted decision, with the one to use instead. */
  replaced: Map<string, string>;
  rules: Rule[];
  pending: number;
}

function parts(model: SystemModel): Parts {
  const tokens = flatten(model.tokens);
  const colors = tokens
    .filter((t): t is { path: string; token: ColorToken } => t.token.$type === "color")
    .sort((a, b) => comparePaths(a.path, b.path));
  const spacing = tokens
    .filter((t): t is { path: string; token: DimensionToken } => t.token.$type === "dimension" && t.path.startsWith("spacing."))
    .sort((a, b) => a.token.$value.value - b.token.$value.value);

  const accepted = new Set(model.decisions.filter((d) => d.status === "accepted").map((d) => d.suggestionId));
  const replaced = new Map<string, string>();
  for (const s of model.suggestions) {
    if (s.kind !== "component" || !accepted.has(s.id)) continue;
    for (const m of s.members) if (m !== s.proposed.name) replaced.set(m, s.proposed.name);
  }
  const label = (c: ComponentEntry, all: readonly ComponentEntry[]) =>
    all.filter((o) => o.name === c.name).length > 1 ? `${c.name} (${c.filePath})` : c.name;
  // Shared components only: pages and the app shell aren't for reuse.
  const components = model.components
    .filter((c) => /(^|\/)components\//.test(c.filePath))
    .filter((c) => !replaced.has(label(c, model.components)) && !replaced.has(c.name))
    .sort((a, b) => compareStrings(a.name, b.name) || compareStrings(a.filePath, b.filePath));

  const decided = new Set(model.decisions.map((d) => d.suggestionId));
  return {
    colors,
    spacing,
    components,
    replaced,
    rules: model.rules.filter((r) => r.enabled),
    pending: model.suggestions.filter((s) => !decided.has(s.id)).length,
  };
}

function summary(name: string, p: Parts): string[] {
  const scale = p.spacing.map((t) => t.token.$value.value);
  const facts = [
    plural(p.colors.length, "color token"),
    scale.length > 0 ? `a ${scale.length}-step spacing scale (${scale[0]}–${scale[scale.length - 1]}px)` : "no spacing scale yet",
    plural(p.components.length, "shared component"),
    plural(p.rules.length, "rule"),
  ];
  const lines = [
    `# ${name} design system`,
    "",
    `${name} is a React + Tailwind app with ${list(facts)}. When you build UI here, use an existing component first, then the tokens below; never hardcoded colors or arbitrary spacing like ${code("p-[13px]")}. Follow the rules, most important first, and check new text against the approved color pairs.`,
  ];
  if (p.pending > 0) {
    lines.push("", `${plural(p.pending, "suggestion")} ${p.pending === 1 ? "is" : "are"} still waiting for review, so ${p.pending === 1 ? "it isn't" : "they aren't"} part of the system yet.`);
  }
  return lines;
}

const isBasicA11y = (r: Rule) => r.category === "accessibility" && !r.basedOn?.length;
const isContrastFix = (r: Rule) => r.category === "accessibility" && (r.basedOn?.length ?? 0) > 0;
const isTop = (r: Rule) => r.category === "component" || r.category === "spacing";

/** Bans first (`no-…`), then which component to use, then spacing; errors before warnings. */
function importance(r: Rule): number {
  const severity = r.severity === "error" ? 0 : 10;
  const kind = r.id.startsWith("no-") ? 0 : r.category === "component" ? 1 : 2;
  return severity + kind;
}

function topRules(p: Parts): string[] {
  const top = p.rules.filter(isTop).sort((a, b) => importance(a) - importance(b) || compareStrings(a.id, b.id));
  if (top.length === 0) return [];
  return ["", "## Most important rules", "", ...top.flatMap((r) => ruleBullet(r))];
}

function accessibility(p: Parts): string[] {
  const opaque = p.colors.filter((c) => c.token.$value.alpha === undefined);
  const lines = ["", "## Accessibility", ""];
  if (opaque.length > 0) {
    lines.push(
      "### Approved text and background pairs",
      "",
      "Ratios are WCAG 2 contrast. Normal text needs 4.5:1; large text (24px, or about 19px and bold), icons and form borders need 3:1.",
      "",
      "| Background | Text (4.5:1 or more) | Large text, icons and borders only (3:1) |",
      "|---|---|---|",
    );
    for (const bg of opaque) {
      const pass: string[] = [];
      const large: string[] = [];
      for (const fg of opaque) {
        if (fg === bg) continue;
        const r = contrastRatio(fg.token.$value.hex, bg.token.$value.hex);
        if (r >= 4.5) pass.push(colorLabel(fg.path));
        else if (r >= 3) large.push(colorLabel(fg.path));
      }
      lines.push(`| ${code(colorLabel(bg.path))} | ${pass.join(", ") || "none"} | ${large.join(", ") || "none"} |`);
    }
  }

  const fixes = p.rules.filter(isContrastFix).sort((a, b) => compareStrings(a.id, b.id));
  if (fixes.length > 0) lines.push("", "### Contrast fixes to follow", "", ...fixes.map((r) => `- ${r.text}`));

  const basics = p.rules.filter(isBasicA11y).sort((a, b) => compareStrings(a.id, b.id));
  if (basics.length > 0) lines.push("", "### Labels, focus and interaction", "", ...basics.flatMap((r) => ruleBullet(r)));

  lines.push("", "These are static checks. They catch some accessibility problems, not all, so passing them doesn't make a screen accessible on its own.");
  return lines;
}

/** Short notes for colors with open contrast problems, e.g. "Not for text on white or gray-50." */
function contrastNotes(model: SystemModel, colors: Parts["colors"]): Map<string, string> {
  const byHex = new Map<string, string>();
  for (const c of colors) if (c.token.$value.alpha === undefined) byHex.set(c.token.$value.hex, colorLabel(c.path));
  const name = (hex: string) => byHex.get(hex) ?? hex;
  const contrast = new Map(model.suggestions.filter((s): s is ContrastSuggestion => s.kind === "contrast").map((s) => [s.id, s]));

  const notes = new Map<string, string>();
  for (const c of colors) {
    const ids = c.token.$extensions?.[STEWARD_EXTENSION]?.contrastIssues ?? [];
    const asText = new Set<string>();
    const asBackground = new Set<string>();
    for (const id of ids) {
      const s = contrast.get(id);
      if (!s) continue;
      if (s.pair.foreground === c.token.$value.hex) asText.add(name(s.pair.background));
      else asBackground.add(name(s.pair.foreground));
    }
    const parts: string[] = [];
    if (asText.size > 0) parts.push(`Not for text on ${list([...asText].sort(comparePaths), "or")}.`);
    if (asBackground.size > 0) parts.push(`Not behind ${list([...asBackground].sort(comparePaths), "or")} text.`);
    if (parts.length > 0) notes.set(c.path, parts.join(" "));
  }
  return notes;
}

function tokens(model: SystemModel, p: Parts): string[] {
  const lines = ["", "## Tokens"];
  if (p.colors.length > 0) {
    const notes = contrastNotes(model, p.colors);
    const solid = p.colors.filter((c) => c.token.$value.alpha === undefined);
    lines.push(
      "",
      `### Colors`,
      "",
      `Use the name in Tailwind classes, e.g. ${code(`bg-${colorLabel(mostUsed(solid.length > 0 ? solid : p.colors).path)}`)}.`,
      "",
      "| Name | Value | Uses | Note |",
      "|---|---|---|---|",
    );
    for (const c of p.colors) {
      const { hex, alpha } = c.token.$value;
      const value = alpha === undefined ? hex : `${hex} at ${Math.round(alpha * 100)}%`;
      lines.push(`| ${[code(colorLabel(c.path)), value, String(usesOf(c)), notes.get(c.path) ?? ""].join(" | ")} |`.replace(/ {2}\|$/, " |"));
    }
  }
  if (p.spacing.length > 0) {
    const first = spacingKey(mostUsed(p.spacing).path);
    lines.push(
      "",
      "### Spacing",
      "",
      `Use the step in any spacing class (${code(`p-${first}`)}, ${code(`gap-${first}`)}, ${code(`mt-${first}`)}). Don't use arbitrary values.`,
      "",
      "| Step | Size |",
      "|---|---|",
      ...p.spacing.map((t) => `| ${code(spacingKey(t.path))} | ${t.token.$value.value}px |`),
    );
  }
  return lines;
}

/** One realistic usage line from what the inventory knows: a variant, a title-like prop, children. */
function usage(c: ComponentEntry): string {
  const props = c.props ?? [];
  const attrs: string[] = [];
  if (c.variants.length > 0) attrs.push(`variant="${c.variants.includes("primary") ? "primary" : [...c.variants].sort(compareStrings)[0]}"`);
  if (props.includes("open")) attrs.push("open={isOpen}");
  const titled = ["label", "title", "heading"].find((t) => props.includes(t));
  if (titled) attrs.push(`${titled}="…"`);
  const open = [c.name, ...attrs].join(" ");
  return props.includes("children") ? `<${open}>…</${c.name}>` : `<${open} />`;
}

function components(p: Parts): string[] {
  if (p.components.length === 0) return [];
  const lines = ["", "## Components", "", "Import paths are from the repo root; adjust them to the importing file."];
  for (const c of p.components) {
    const importPath = c.filePath.replace(/\.[cm]?[jt]sx?$/, "");
    lines.push("", `### ${c.name}`, "", `${code(`import { ${c.name} } from "${importPath}";`)}`, "");
    if (c.props && c.props.length > 0) lines.push(`- Props: ${c.props.map(code).join(", ")}`);
    if (c.variants.length > 0) lines.push(`- Variants: ${c.variants.map(code).join(", ")}`);
    const instead = [...p.replaced].filter(([, keep]) => keep === c.name).map(([old]) => code(old.replace(/ \(.*\)$/, "")));
    if (instead.length > 0) lines.push(`- Use instead of ${list(instead, "or")}`);
    lines.push(`- Example: ${code(usage(c))}`);
  }
  return lines;
}

function otherRules(p: Parts): string[] {
  const rest = p.rules.filter((r) => !isTop(r) && !isBasicA11y(r) && !isContrastFix(r));
  if (rest.length === 0) return [];
  const order = ["color", "accessibility", "spacing", "component"];
  // Within a category, rules about tokens follow the token order (gray-50 before gray-100).
  const target = (r: Rule) => {
    const t = r.appliesTo.find((x) => x.kind === "token" || x.kind === "token-group");
    return t && "path" in t ? t.path : "";
  };
  rest.sort((a, b) => order.indexOf(a.category) - order.indexOf(b.category) || comparePaths(target(a), target(b)) || compareStrings(a.id, b.id));
  return ["", "## Other rules", "", ...rest.flatMap((r) => ruleBullet(r))];
}

/**
 * Pure: turns the system model into design.md, a short, scannable brief an
 * AI coding tool can read. Only what people decided goes in: tokens, shared
 * components (minus ones merged away) and enabled rules. Pending suggestions
 * are only counted. Same model in, same text out.
 */
export function generateDesignMd(model: SystemModel, options: DesignMdOptions = {}): string {
  const name = options.name ?? "This project";
  const p = parts(model);
  const lines = [
    `${DESIGN_MD_MARKER} Don't edit by hand: run \`steward context --file\` to update. -->`,
    "",
    ...summary(name, p),
    ...topRules(p),
    ...accessibility(p),
    ...tokens(model, p),
    ...components(p),
    ...otherRules(p),
  ];
  return `${lines.join("\n")}\n`;
}
