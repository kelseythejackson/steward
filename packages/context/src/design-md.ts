import {
  compareStrings,
  isToken,
  STEWARD_EXTENSION,
  type ColorToken,
  type ComponentEntry,
  type ContrastSuggestion,
  type DimensionToken,
  type Rule,
  type SystemModel,
  type TokenGroup,
} from "@steward/model";

/** First line of every generated design.md, so `steward context --file` knows it may overwrite the file. */
export const DESIGN_MD_MARKER = "<!-- Generated by Steward from .steward/system.json.";

export interface DesignMdOptions {
  /** The project's name for the title, e.g. the repo folder name. */
  name?: string;
}

// ---------------------------------------------------------------------------
// Small helpers
// ---------------------------------------------------------------------------

const code = (s: string) => `\`${s}\``;
const plural = (n: number, one: string, many = `${one}s`) => `${n} ${n === 1 ? one : many}`;
const list = (xs: readonly string[], joiner = "and") =>
  xs.length <= 1 ? (xs[0] ?? "") : `${xs.slice(0, -1).join(", ")} ${joiner} ${xs[xs.length - 1]}`;

/** `color.gray.400` → `gray-400`, the name used in Tailwind classes. Matches the scanner's labels. */
const colorLabel = (path: string) => path.replace(/^color\./, "").replaceAll(".", "-");
/** `spacing.2_5` → `2.5`, the Tailwind class suffix. */
const spacingKey = (path: string) => path.replace(/^spacing\./, "").replace("_", ".");

/** WCAG 2 contrast ratio between two opaque hex colors. */
export function contrastRatio(a: string, b: string): number {
  const lum = (hex: string) => {
    const [r, g, bl] = [1, 3, 5].map((i) => {
      const c = parseInt(hex.slice(i, i + 2), 16) / 255;
      return c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
    });
    return 0.2126 * r! + 0.7152 * g! + 0.0722 * bl!;
  };
  const [hi, lo] = [lum(a), lum(b)].sort((x, y) => y - x);
  return (hi! + 0.05) / (lo! + 0.05);
}

/** Rounds down, so a failing 4.49 never shows as a passing 4.5. */
const ratioText = (r: number) => `${(Math.floor(r * 10 + 1e-9) / 10).toFixed(1)}:1`;

function flatten(group: TokenGroup, prefix = ""): { path: string; token: ColorToken | DimensionToken }[] {
  const out: { path: string; token: ColorToken | DimensionToken }[] = [];
  for (const key of Object.keys(group).sort(compareStrings)) {
    const node = group[key]!;
    const path = prefix ? `${prefix}.${key}` : key;
    if (isToken(node)) out.push({ path, token: node });
    else out.push(...flatten(node, path));
  }
  return out;
}

/** Orders `gray.50, gray.100, … gray.900` numerically instead of as text. */
function comparePaths(a: string, b: string): number {
  const pa = a.split(/[.-]/);
  const pb = b.split(/[.-]/);
  for (let i = 0; i < Math.max(pa.length, pb.length); i++) {
    const x = pa[i] ?? "";
    const y = pb[i] ?? "";
    if (x === y) continue;
    const nx = Number(x.replace("_", "."));
    const ny = Number(y.replace("_", "."));
    if (x !== "" && y !== "" && !Number.isNaN(nx) && !Number.isNaN(ny)) return nx - ny;
    return compareStrings(x, y);
  }
  return 0;
}

const usesOf = (t: { token: ColorToken | DimensionToken }) => t.token.$extensions?.[STEWARD_EXTENSION]?.uses ?? 0;
/** The most used token, for examples; ties go to the earlier one. */
const mostUsed = <T extends { token: ColorToken | DimensionToken }>(ts: readonly T[]): T => ts.reduce((best, t) => (usesOf(t) > usesOf(best) ? t : best));

/** A rule's examples as two indented lines. Multi-line examples are joined so each stays one line. */
function examples(r: Rule): string[] {
  const one = (s: string) => code(s.replace(/\s*\n\s*/g, " "));
  return [`  - ✓ ${one(r.examples.right)}`, `  - ✗ ${one(r.examples.wrong)}`];
}

const ruleBullet = (r: Rule, withExamples = true) => [`- ${r.text}`, ...(withExamples ? examples(r) : [])];

